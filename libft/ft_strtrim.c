#include "libft.h"
#include <stdlib.h>

char	*ft_strtrim(char const *s1, char const *set)
{
	size_t	i;
	size_t	n;

	if (!s1 || !set)
		return (NULL);
	i = 0;
	while (s1[i] && ft_strchr(set, s1[i]))
		i++;
	n = ft_strlen(s1);
	while (n > i && ft_strchr(set, s1[n - 1]))
		n--;
	return (ft_substr(s1, i, n - i));
}
